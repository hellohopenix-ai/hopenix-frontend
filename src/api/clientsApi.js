/* ======================================================================
   clientsApi.js — real backend calls for ClientsPage.jsx / ClientPortal.jsx
   / ClientIntakeForm.jsx.

   Matches AuthContext.jsx's own conventions exactly:
     - token read straight from localStorage["hopenix_auth_token"]
       (same TOKEN_KEY AuthContext already uses — no need to pass a
       token around, this reads it itself, same as AuthContext's own
       internal apiFetch does)
     - "Authorization: Token <key>" header (DRF TokenAuthentication)
     - base URL http://127.0.0.1:8000/api + app path

   STEP 2 of the staged rollout only wires up plain Client CRUD
   (dashboard.Client) — Projects/Modules/Invoices/ModuleRequests come in
   later steps once this is confirmed working.
====================================================================== */

// FIX (Add Client behaving "local-only" — Priority 1): this used to be a
// hardcoded "http://127.0.0.1:8000/api" literal with no way to point it
// anywhere else. clientPortalApi.js already solved this correctly — read
// VITE_API_BASE_URL, then ALWAYS normalize to end in exactly one "/api"
// regardless of whether the env var itself already includes it. (A first
// pass here only stripped a trailing slash, which broke as soon as
// VITE_API_BASE_URL was set WITHOUT "/api" on the end — every request in
// this file silently 404'd because the path builders below always assume
// API_BASE_URL already ends in "/api".) This now matches
// clientPortalApi.js's own hostBase normalization exactly.
import { API_BASE_URL } from "../apiConfig.js";
const TOKEN_KEY = "hopenix_auth_token";

async function apiFetch(path, options = {}) {
  const token = localStorage.getItem(TOKEN_KEY);
  const isFormData = options.body instanceof FormData;
  const headers = { ...(options.headers || {}) };
  if (!isFormData) headers["Content-Type"] = "application/json";
  if (token) headers["Authorization"] = `Token ${token}`;

  const res = await fetch(`${API_BASE_URL}${path}`, { ...options, headers });
  let data = null;
  try {
    data = await res.json();
  } catch {
    // some responses (e.g. 204 No Content on delete) have no body
  }
  if (!res.ok) {
    const message =
      (data && (data.detail || data.error || Object.values(data)[0])) || "Something went wrong. Please try again.";
    throw new Error(Array.isArray(message) ? message[0] : String(message));
  }
  return data;
}

/* ---------------------------------------------------------------------
   CLIENTS — dashboard.Client
--------------------------------------------------------------------- */

export function listClients(params = {}) {
  const qs = new URLSearchParams(params).toString();
  return apiFetch(`/dashboard/clients/${qs ? `?${qs}` : ""}`);
}

export function getClient(id) {
  return apiFetch(`/dashboard/clients/${id}/`);
}

export function createClient(data) {
  // FIX (client photo never reached the backend): the Add/Edit Client
  // form now sometimes needs to send a real file upload (the picked
  // avatar photo) alongside the rest of the fields — see
  // ClientsPage.jsx's buildClientPayload. A FormData body must be
  // passed straight through as-is; JSON.stringify()-ing it would just
  // serialize it to "[object FormData]".
  const isForm = data instanceof FormData;
  return apiFetch("/dashboard/clients/", { method: "POST", body: isForm ? data : JSON.stringify(data) });
}

export function updateClient(id, data) {
  const isForm = data instanceof FormData;
  return apiFetch(`/dashboard/clients/${id}/`, { method: "PATCH", body: isForm ? data : JSON.stringify(data) });
}

export function deleteClient(id) {
  return apiFetch(`/dashboard/clients/${id}/`, { method: "DELETE" });
}

export function generatePortalAccess(clientId) {
  return apiFetch(`/dashboard/clients/${clientId}/portal-access/`, { method: "POST" });
}

// Matches ClientPortal.jsx's LoginScreen — Client ID + email + the portal
// password generated by generatePortalAccess(). No auth header needed
// (AllowAny on the backend, which throttles + locks out repeated failures).
export function portalLogin(clientId, email, password) {
  return apiFetch(`/dashboard/clients/portal-login/`, {
    method: "POST",
    body: JSON.stringify({ id: clientId, email, password }),
  });
}

