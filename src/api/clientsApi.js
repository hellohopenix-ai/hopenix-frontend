/** Upload a new document for a client.
 *  `file`    — a File/Blob object (required)
 *  `clientId` — the dashboard.Client pk
 *  `projectId` — optional projects.Project pk to link the document to
 */
export function uploadDocument(clientId, file, projectId) {
  const form = new FormData();
  form.append("file", file);
  form.append("file_name", file.name);
  form.append("client", clientId);
  if (projectId) form.append("project", projectId);
  return apiFetch("/dashboard/documents/", { method: "POST", body: form });
}

/** Delete a document by id. Also deletes the file from disk on the backend. */
export function deleteDocument(documentId) {
  return apiFetch(`/dashboard/documents/${documentId}/`, { method: "DELETE" });
}

